"use client";
import Link from "next/link";
import { download } from "@/components/workspace/format";
import { Card } from "@/components/workspace/ui";
import {
  COURT_RECORDS,
  CPLR_5501,
  type CourtRecord,
} from "@/lib/demo/court-records";
import {
  FINDINGS,
  LABEL,
  LIMITATIONS,
  RESEARCH_QUESTION,
  STEPS,
  type Citation,
} from "@/lib/demo/gonzalez-workflow";
import { OpenRecord, pageLabel } from "./PublicRecord";

const cite = (c: Citation) => {
  const r: CourtRecord = COURT_RECORDS[c.source];
  return `${r.caseName}, ${r.docket}, ${pageLabel(c)}`;
};

/** Plain-text memo of the prepared analysis, for attorney review. */
function memoText() {
  const lines = [
    `RESEARCH MEMORANDUM — DRAFT FOR ATTORNEY REVIEW`,
    `${LABEL}. Prepared by hand for the Casevex demo; not generated by Casevex AI.`,
    ``,
    `QUESTION`,
    RESEARCH_QUESTION,
    ``,
    `FINDINGS`,
  ];
  FINDINGS.forEach((f, i) => {
    lines.push(``, `${i + 1}. ${f.heading}`, f.summary);
    for (const c of f.citations)
      lines.push(`   ${c.speaker}: “${c.quote}” (${cite(c)})`);
  });
  lines.push(``, `SOURCES`);
  for (const r of Object.values(COURT_RECORDS).filter(
    (r) => r.id === "gonzalez" || r.id === "malmberg",
  ))
    lines.push(
      `- ${r.caseName}, ${r.citation}, ${r.docket} (${r.decided}). File ${r.fileName}, SHA-256 ${r.sha256}. Source: ${r.sourceUrl}`,
    );
  lines.push(`- ${CPLR_5501.title}. Official text: ${CPLR_5501.sourceUrl}`);
  lines.push(``, `LIMITATIONS`, ...LIMITATIONS.map((l) => `- ${l}`));
  return lines.join("\n");
}

function CitationBlock({ c }: { c: Citation }) {
  const r = COURT_RECORDS[c.source];
  return (
    <figure className="workflow-citation">
      <figcaption>
        <b>{c.speaker}</b> · <i>{r.caseName}</i> · {pageLabel(c)}
      </figcaption>
      <blockquote>{c.quote}</blockquote>
      <OpenRecord record={r} page={c.page} />
    </figure>
  );
}

/** The prepared research workflow for the Gonzalez demo matter. */
export default function ResearchWorkflow({ backHref }: { backHref: string }) {
  return (
    <div className="page-body expanded-matter-view">
      <nav className="expanded-matter-nav" aria-label="Research workflow">
        <span className="compare-label">{LABEL}</span>
        <Link href={backHref}>Back to overview ↙</Link>
      </nav>
      <div
        className="expanded-matter-content scroll workflow-view"
        tabIndex={0}
        aria-label="Legal research workflow"
      >
        <h2 className="compare-title">Legal research workflow</h2>
        <p className="workflow-notice">
          This analysis was prepared and checked by hand to show the review
          workflow. Casevex AI did not write it, and live research is turned off
          in the demo. Every quotation below is exact and links to its page in
          the original opinion.
        </p>
        <Card title="Research question">
          <p className="workflow-question">“{RESEARCH_QUESTION}”</p>
        </Card>
        <Card title="Workflow">
          <ol className="workflow-steps">
            {STEPS.map((s) => (
              <li key={s.title}>
                <b>{s.title}.</b> {s.detail}
              </li>
            ))}
          </ol>
        </Card>
        {FINDINGS.map((f, i) => (
          <Card key={f.heading} title={`${i + 1}. ${f.heading}`}>
            <p>{f.summary}</p>
            {f.heading === "Statutory authority" && (
              <p>
                <a
                  href={CPLR_5501.sourceUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                >
                  Read {CPLR_5501.title} on the {CPLR_5501.sourceName} site ↗
                </a>
              </p>
            )}
            {f.citations.map((c) => (
              <CitationBlock key={c.quote} c={c} />
            ))}
          </Card>
        ))}
        <Card title="Limitations">
          <ul>
            {LIMITATIONS.map((l) => (
              <li key={l}>{l}</li>
            ))}
          </ul>
        </Card>
        <Card title="Research memorandum">
          <p>
            Download the findings above as a plain-text memo with pinpoint
            citations, file fingerprints and limitations, for attorney review.
          </p>
          <button
            type="button"
            onClick={() =>
              download("gonzalez-research-memo-draft.txt", memoText())
            }
          >
            Download memo draft
          </button>
        </Card>
      </div>
    </div>
  );
}
