/**
 * Prints the AI routing table and the monthly cost estimate as Markdown.
 *   npm run ai:report            # to the terminal
 *   npm run ai:report -- --write # also rewrites docs/ai/COST_ESTIMATE.md
 */
import { writeFileSync } from "node:fs";
import {
  AI_FUNCTIONS,
  MODELS,
  PILOT_FIRM,
  PIPELINES,
  PRICES_AS_OF,
  TIERS,
  isModelId,
  pipelineCost,
  resolveRoute,
  scenarioCost,
} from "../lib/ai";

const usd = (n: number) =>
  n >= 1
    ? `$${n.toFixed(2)}`
    : n >= 0.01
      ? `$${n.toFixed(3)}`
      : `$${n.toFixed(5)}`;
const label = (id: string) => (isModelId(id) ? MODELS[id].label : id);

const lines: string[] = [];
lines.push(
  "# AI cost estimate",
  "",
  `Generated by \`npm run ai:report -- --write\`. List prices as of ${PRICES_AS_OF}; run \`npm run ai:check\` to confirm them against OpenRouter.`,
  "",
  "## Tiers",
  "",
  "| Tier | Models (primary first) | Per-call ceiling | Used for |",
  "| --- | --- | --- | --- |",
);
for (const t of Object.values(TIERS))
  lines.push(
    `| ${t.tier} | ${t.chain.map(label).join(" → ")} | ${usd(t.maxUsdPerCall)} | ${t.description} |`,
  );

const { rows, totalUsdPerMonth, byTier } = scenarioCost(PILOT_FIRM);
lines.push(
  "",
  "## Functions",
  "",
  "| Function | Tier | Data | Models | Typical in / out tokens | Per call | Worst call | Calls/mo | $/mo |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
);
for (const r of rows) {
  const fn = AI_FUNCTIONS[r.key];
  const route = resolveRoute(r.key, {});
  lines.push(
    `| \`${r.key}\` ${fn.label} | ${r.tier} | ${fn.dataClass} | ${route.chain.map(label).join(" → ")} | ${fn.typicalInputTokens.toLocaleString("en-US")} / ${fn.typicalOutputTokens.toLocaleString("en-US")} | ${usd(r.usdPerCall)} | ${usd(r.usdPerCallWorst)} | ${Math.round(r.calls).toLocaleString("en-US")} | ${usd(r.usdPerMonth)} |`,
  );
}

lines.push(
  "",
  "## Per action",
  "",
  "| Action | Typical cost |",
  "| --- | --- |",
);
for (const name of Object.keys(PIPELINES))
  lines.push(`| ${name} | ${usd(pipelineCost(name))} |`);

lines.push(
  "",
  `## Monthly: ${PILOT_FIRM.name}`,
  "",
  PILOT_FIRM.description,
  "",
  "| Tier | $/month | Share |",
  "| --- | --- | --- |",
);
for (const [tier, v] of Object.entries(byTier).sort((a, b) => b[1] - a[1]))
  lines.push(
    `| ${tier} | ${usd(v)} | ${((v / totalUsdPerMonth) * 100).toFixed(0)}% |`,
  );
lines.push(
  `| **total** | **${usd(totalUsdPerMonth)}** | |`,
  "",
  "OpenRouter charges a fee on credit purchases on top of model prices. These estimates exclude that fee, embeddings, OCR and hosting.",
  "",
);

const md = lines.join("\n");
console.log(md);
if (process.argv.includes("--write"))
  writeFileSync(new URL("../docs/ai/COST_ESTIMATE.md", import.meta.url), md);
